#!/usr/bin/env swift
// Builds the horizontal logo (app icon + "Many Displays" wordmark) from Resources/AppIcon.svg:
// logo.svg / logo.png for light backgrounds and logo-dark.svg / logo-dark.png for dark ones.
// The wordmark is set in Inter Display SemiBold (SIL Open Font License, https://rsms.me/inter/) and
// converted to outlines, so the SVG files depend on no font. Inter is not in the repo: download the
// release zip and point --font at extras/otf/InterDisplay-SemiBold.otf.
// Usage: swift scripts/make-logo.swift --font /path/to/InterDisplay-SemiBold.otf [--out Resources/Brand] [--text "Many Displays"]
import AppKit

var fontPath: String?
var outDir = "Resources/Brand"
var svgPath = "Resources/AppIcon.svg"
var text = "Many Displays"
var args = Array(CommandLine.arguments.dropFirst())
while !args.isEmpty {
    let a = args.removeFirst()
    switch a {
    case "--font": fontPath = args.removeFirst()
    case "--out": outDir = args.removeFirst()
    case "--svg": svgPath = args.removeFirst()
    case "--text": text = args.removeFirst()
    default: print("unknown argument \(a)"); exit(2)
    }
}

guard let fontPath else { print("usage: swift scripts/make-logo.swift --font InterDisplay-SemiBold.otf"); exit(2) }
guard let descriptors = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: fontPath) as CFURL) as? [CTFontDescriptor],
      let descriptor = descriptors.first else { print("cannot read font \(fontPath)"); exit(1) }
guard let icon = try? String(contentsOfFile: svgPath, encoding: .utf8),
      let open = icon.range(of: "<svg"), let openEnd = icon[open.upperBound...].range(of: ">"),
      let close = icon.range(of: "</svg>", options: .backwards) else { print("cannot parse \(svgPath)"); exit(1) }
let iconBody = String(icon[openEnd.upperBound ..< close.lowerBound])

// Geometry: the icon tile is `tile` points tall, the wordmark's cap height is half of that.
let tile: CGFloat = 160, gap: CGFloat = 44
let probe = CTFontCreateWithFontDescriptor(descriptor, 100, nil)
let fontSize = (tile * 0.5) / (CTFontGetCapHeight(probe) / 100)
let font = CTFontCreateWithFontDescriptor(descriptor, fontSize, nil)
let capHeight = CTFontGetCapHeight(font)
let baseline = tile / 2 + capHeight / 2
let textX = tile + gap

func number(_ v: CGFloat) -> String {
    var s = String(format: "%.2f", v)
    while s.hasSuffix("0") {
        s.removeLast()
    }
    if s.hasSuffix(".") {
        s.removeLast()
    }
    return s == "-0" ? "0" : s
}

func svgPath(_ path: CGPath) -> String {
    var d = ""
    path.applyWithBlock { element in
        let p = element.pointee.points
        switch element.pointee.type {
        case .moveToPoint: d += "M\(number(p[0].x)) \(number(p[0].y))"
        case .addLineToPoint: d += "L\(number(p[0].x)) \(number(p[0].y))"
        case .addQuadCurveToPoint: d += "Q\(number(p[0].x)) \(number(p[0].y)) \(number(p[1].x)) \(number(p[1].y))"
        case .addCurveToPoint:
            d += "C\(number(p[0].x)) \(number(p[0].y)) \(number(p[1].x)) \(number(p[1].y)) \(number(p[2].x)) \(number(p[2].y))"
        case .closeSubpath: d += "Z"
        @unknown default: break
        }
    }
    return d
}

/// Lay the text out with CoreText (kerning included) and turn every glyph into outlines.
let line = CTLineCreateWithAttributedString(NSAttributedString(
    string: text,
    attributes: [kCTFontAttributeName as NSAttributedString.Key: font]
))
var wordmark = ""
for run in CTLineGetGlyphRuns(line) as! [CTRun] {
    let count = CTRunGetGlyphCount(run)
    var glyphs = [CGGlyph](repeating: 0, count: count)
    var positions = [CGPoint](repeating: .zero, count: count)
    CTRunGetGlyphs(run, CFRangeMake(0, 0), &glyphs)
    CTRunGetPositions(run, CFRangeMake(0, 0), &positions)
    for (glyph, position) in zip(glyphs, positions) {
        // Flip y (fonts are y-up, SVG is y-down) and move to the baseline.
        var transform = CGAffineTransform(translationX: textX + position.x, y: baseline - position.y).scaledBy(x: 1, y: -1)
        if let path = CTFontCreatePathForGlyph(font, glyph, &transform) {
            wordmark += svgPath(path)
        }
    }
}

let textWidth = CGFloat(CTLineGetTypographicBounds(line, nil, nil, nil))
let width = (textX + textWidth).rounded(.up)
let scale = tile / 824 // icon tile (824 of the 1024 canvas) → `tile` points
let offset = -100 * scale

func logo(textColor: String) -> String {
    """
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \(number(width)) \(number(tile))" width="\(number(width))" height="\(number(tile))">
      <!-- Many Displays logo. Generated by scripts/make-logo.swift from Resources/AppIcon.svg; wordmark: Inter Display SemiBold (OFL) as outlines. -->
      <g transform="translate(\(number(offset)) \(number(offset))) scale(\(number(scale)))">\(iconBody)</g>
      <path fill="\(textColor)" d="\(wordmark)"/>
    </svg>

    """
}

try! FileManager.default.createDirectory(atPath: outDir, withIntermediateDirectories: true)
for (name, color) in [("logo", "#1B1F3B"), ("logo-dark", "#FFFFFF")] {
    let svg = logo(textColor: color)
    try! svg.write(toFile: "\(outDir)/\(name).svg", atomically: true, encoding: .utf8)
    guard let image = NSImage(data: svg.data(using: .utf8)!) else { print("cannot render \(name).svg"); exit(1) }
    let w = Int(width * 2), h = Int(tile * 2) // 2x PNG for README and the website
    let rep = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8, samplesPerPixel: 4,
        hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
    )!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSGraphicsContext.current?.imageInterpolation = .high
    image.draw(in: NSRect(x: 0, y: 0, width: w, height: h), from: .zero, operation: .sourceOver, fraction: 1)
    NSGraphicsContext.restoreGraphicsState()
    try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: "\(outDir)/\(name).png"))
    print("Wrote \(outDir)/\(name).svg and .png (\(w)x\(h))")
}
